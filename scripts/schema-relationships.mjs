#!/usr/bin/env node
/**
 * docs/SCHEMA_RELATIONSHIPS.md from the baseline export of the live database
 * (medris-backend/src/database/baseline/01-public-schema.sql): every table, what it is for, and how the tables
 * point at each other (foreign keys), plus a diagram of the core ones.
 *
 *   npm run schema:relationships           # rewrites the page
 *   npm run schema:relationships -- --check
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = fs.readFileSync(path.join(root, "medris-backend/src/database/baseline/01-public-schema.sql"), "utf8");

const tables = new Map();
for (const m of schema.matchAll(/^CREATE TABLE public\.(\w+) \(\n([\s\S]*?)\n\);/gm)) {
  const columns = m[2]
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => /^[a-z_"]/.test(l) && !/^CONSTRAINT /.test(l))
    .map((l) => l.split(" ")[0].replaceAll('"', ""));
  tables.set(m[1], { columns, comment: "", refs: [], referencedBy: [] });
}
for (const m of schema.matchAll(/^COMMENT ON TABLE public\.(\w+) IS '((?:[^']|'')*)';/gm)) {
  if (tables.has(m[1])) tables.get(m[1]).comment = m[2].replaceAll("''", "'");
}
for (const m of schema.matchAll(/ALTER TABLE ONLY public\.(\w+)\n\s+ADD CONSTRAINT \w+ FOREIGN KEY \(([^)]+)\) REFERENCES (\w+)\.(\w+)\(([^)]+)\)([^;]*);/g)) {
  const [, from, cols, refSchema, to, toCols, rest] = m;
  const onDelete = /ON DELETE (CASCADE|SET NULL|RESTRICT|SET DEFAULT)/.exec(rest)?.[1]?.toLowerCase() ?? "no action";
  const ref = { from, cols, to: refSchema === "public" ? to : `${refSchema}.${to}`, toCols, onDelete };
  tables.get(from)?.refs.push(ref);
  if (refSchema === "public") tables.get(to)?.referencedBy.push(ref);
}

const names = [...tables.keys()].sort();
const refCount = names.reduce((n, t) => n + tables.get(t).refs.length, 0);
let md = `# Database tables and how they relate\n\nGenerated by \`npm run schema:relationships\` from the baseline export of the live database\n(\`medris-backend/src/database/baseline/01-public-schema.sql\`) - do not edit by hand. Refresh the baseline first\n(\`npm run db:baseline:update -w medris-backend\`) when the live schema changes.\n\n**${names.length} tables, ${refCount} links** (foreign keys). "on delete cascade" means deleting the row it points at also\ndeletes this one; "set null" clears the link; "no action" refuses the delete while rows still point at it.\n\n`;

// The core: who sells, who buys, what is sold, how it is paid.
const core = ["users", "vendors", "products", "vendor_packages", "package_items", "orders", "order_items", "payments", "reviews", "disputes", "conversations", "messages", "notifications", "favorites", "vendor_follows", "cart_items", "sectors", "categories"];
md += "## The core, as a diagram\n\n```mermaid\nerDiagram\n";
for (const t of core.filter((x) => tables.has(x))) {
  for (const r of tables.get(t).refs) if (core.includes(r.to)) md += `  ${r.to} ||--o{ ${t} : "${r.cols.replaceAll('"', "")}"\n`;
}
md += "```\n\n## Every table\n\n";
for (const t of names) {
  const info = tables.get(t);
  md += `### \`${t}\`\n\n${info.comment ? `${info.comment}\n\n` : ""}Columns: ${info.columns.map((c) => `\`${c}\``).join(", ")}\n\n`;
  if (info.refs.length) md += `Points at: ${info.refs.map((r) => `\`${r.cols}\` -> \`${r.to}\` (${r.onDelete})`).join("; ")}\n\n`;
  if (info.referencedBy.length) md += `Pointed at by: ${[...new Set(info.referencedBy.map((r) => `\`${r.from}.${r.cols}\``))].join(", ")}\n\n`;
}

const out = path.join(root, "docs", "SCHEMA_RELATIONSHIPS.md");
if (process.argv.includes("--check")) {
  if ((fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "") !== md) {
    console.error("docs/SCHEMA_RELATIONSHIPS.md is out of date: run `npm run schema:relationships`.");
    process.exit(1);
  }
} else fs.writeFileSync(out, md);
console.log(`${names.length} tables, ${refCount} links`);
